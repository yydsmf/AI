# Utility functions

def set_run_font(run, size=10.5, bold=None, color=None):
    run.font.name = '宋体'
    run._element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
    run.font.size = Pt(size)
    if bold is not None: run.bold = bold
    if color: run.font.color.rgb = color


def add_para(doc, text='', size=10.5, bold=False, align=None, space_after=3, first_line=True):
    p=doc.add_paragraph()
    if align is not None: p.alignment=align
    pf=p.paragraph_format
    pf.space_after=Pt(space_after)
    pf.line_spacing=1.12
    if first_line: pf.first_line_indent=Cm(0.74)
    r=p.add_run(text)
    set_run_font(r,size,bold)
    return p


def add_heading(doc, text, level=1):
    p=doc.add_paragraph()
    p.paragraph_format.space_before=Pt(8 if level==1 else 5)
    p.paragraph_format.space_after=Pt(4)
    p.paragraph_format.keep_with_next=True
    r=p.add_run(text)
    set_run_font(r, 15 if level==1 else 12, True)
    return p

